def format_datetime_locale(value: datetime | None, locale: Locale, timezone: str) -> str:
    if value is None:
        return "–"
    local = value.astimezone(ZoneInfo(timezone))
    if locale == "de":
        return local.strftime("%d.%m.%Y · %H:%M")
    if locale == "en":
        return f"{_MONTHS[locale][local.month - 1]} {local.day}, {local.year} · {local:%H:%M}"
    if locale == "zh-CN":
        return f"{local.year}年{local.month}月{local.day}日 {local:%H:%M}"
    return f"{local.day} {_MONTHS[locale][local.month - 1]} {local.year} · {local:%H:%M}"


def format_duration_locale(minutes: int | None, locale: Locale) -> str:
    if not minutes:
        return "–"
    hours, rest = divmod(minutes, 60)
    parts: list[str] = []
    if hours:
        parts.append(translate(locale, "duration.hours", count=hours))
    if rest:
        parts.append(translate(locale, "duration.minutes", count=rest))
    return " ".join(parts)


def catalog_is_complete() -> bool:
    expected = set(MESSAGES["en"])
    return all(set(messages) == expected for messages in MESSAGES.values())


_LOCALE_TOKEN_RE = re.compile(r"^[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]{2,8})*$")


def valid_locale_token(value: str) -> bool:
    return bool(_LOCALE_TOKEN_RE.fullmatch(value))
