def normalize_locale(
    value: str | None, *, fallback: Locale | None = DEFAULT_LOCALE
) -> Locale | None:
    if not value:
        return fallback
    normalized = value.strip().replace("_", "-").casefold()
    if not normalized:
        return fallback
    primary = normalized.split("-", 1)[0]
    if primary == "zh":
        return "zh-CN"
    if primary in {"de", "en", "hi", "es"}:
        return cast(Locale, primary)
    return fallback


def detect_browser_locale(header: str | None) -> Locale:
    """Return the best supported locale from a standards-style Accept-Language header."""

    candidates: list[tuple[float, int, str]] = []
    for position, raw_part in enumerate((header or "").split(",")):
        part = raw_part.strip()
        if not part:
            continue
        language, *parameters = (piece.strip() for piece in part.split(";"))
        quality = 1.0
        for parameter in parameters:
            if not parameter.casefold().startswith("q="):
                continue
            try:
                quality = float(parameter[2:])
            except ValueError:
                quality = 0.0
        if not 0 < quality <= 1:
            continue
        candidates.append((quality, position, language))
    candidates.sort(key=lambda item: (-item[0], item[1]))
    for _, _, language in candidates:
        if language == "*":
            return DEFAULT_LOCALE
        matched = normalize_locale(language, fallback=None)
        if matched is not None:
            return matched
    return DEFAULT_LOCALE


def request_locale(request: Request, user: object | None = None) -> Locale:
    candidate = user or getattr(request.state, "user", None)
    stored = getattr(candidate, "language", None)
    normalized = normalize_locale(stored, fallback=None)
    return normalized or detect_browser_locale(request.headers.get("accept-language"))


